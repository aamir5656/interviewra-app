async def test_start_streams_session_tokens_done_and_saves(client: AsyncClient, db: AsyncSession, use_fake_llm) -> None:
    provider = use_fake_llm(tool_responses=["Hi, I'm Alex. What is an index?"], texts=["Backend Junior Interview."])
    h = await guest(client)
    r = await start(client, h)
    assert r.status_code == 200 and r.headers["content-type"].startswith("text/event-stream")
    events = parse_sse(r.text)
    assert [e for e, _ in events][0] == "session" and events[-1][0] == "done"
    assert "".join(d["text"] for e, d in events if e == "token") == "Hi, I'm Alex. What is an index?"
    assert events[-1][1]["ready_to_end"] is False
    sid = events[0][1]["session_id"]

    session = await db.scalar(select(InterviewSession).where(InterviewSession.id == sid))
    assert session.current_question_index == 1 and session.status == "active"  # the server counted main question 1
    assert session.title == "Backend Junior Interview"  # title generated by the background task
    msgs = (await db.scalars(select(Message).where(Message.session_id == session.id))).all()
    assert [m.role for m in msgs] == ["assistant"] and str(msgs[0].id) == events[-1][1]["message_id"]
    assert "Backend Engineer" in provider.calls[0]["system"]
    assert {t.name for t in provider.calls[0]["tools"]} == {"search_question_bank"}  # guest: no memory tool; the topic is chosen by the server and end_interview comes last


LONG_ANSWER = ("An index speeds up reads because the database can jump to matching rows instead of scanning the whole "
               "table, but every insert must also update the index, so I would measure with EXPLAIN first.")


async def test_answer_streams_reply_and_wraps_answer(client: AsyncClient, db: AsyncSession, use_fake_llm) -> None:
    provider = use_fake_llm(tool_responses=["Question one?", "Nice point. Question two?"], texts=["Title"])
    h = await guest(client)
    sid = await start_ok(client, h)
    r = await client.post(f"{API}/interviews/{sid}/answer", json={"content": "  " + LONG_ANSWER + "  "}, headers=h)
    events = parse_sse(r.text)
    assert events[-1][0] == "done" and events[-1][1]["ready_to_end"] is False
    assert "".join(d["text"] for e, d in events if e == "token") .split() == ["Nice", "point.", "Question", "two?"]  # lead-in and question are separate paragraphs
    last = provider.calls[-1]["messages"]
    assert last[-1].content == f"<candidate_answer>\n{LONG_ANSWER}\n</candidate_answer>"
    roles = [m.role for m in (await db.scalars(select(Message).where(Message.session_id == sid).order_by(Message.created_at))).all()]
    assert roles == ["assistant", "user", "assistant"]


