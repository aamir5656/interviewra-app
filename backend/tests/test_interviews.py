async def test_history_list_detail_rename_delete(client: AsyncClient, use_fake_llm) -> None:
    use_fake_llm(tool_responses=["Q1?", "Q1b?", "Q2?"], texts=["T1", "T2", "T3"])
    h = await guest(client)
    ids = [await start_ok(client, h) for _ in range(3)]
    listing = (await client.get(f"{API}/interviews?limit=2", headers=h)).json()
    assert listing["total"] == 3 and listing["limit"] == 2 and [i["id"] for i in listing["items"]] == ids[::-1][:2]
    page2 = (await client.get(f"{API}/interviews?limit=2&offset=2", headers=h)).json()
    assert [i["id"] for i in page2["items"]] == [ids[0]]
    assert (await client.get(f"{API}/interviews?limit=0", headers=h)).status_code == 422

    detail = (await client.get(f"{API}/interviews/{ids[0]}", headers=h)).json()
    assert [m["role"] for m in detail["messages"]] == ["assistant"] and detail["feedback"] is None

    url = f"{API}/interviews/{ids[0]}"
    assert (await client.patch(url, json={"title": "  My mock  "}, headers=h)).json()["title"] == "My mock"
    assert (await client.patch(url, json={"title": " "}, headers=h)).status_code == 422
    assert (await client.patch(url, json={"title": "x" * 81}, headers=h)).status_code == 422
    assert (await client.delete(url, headers=h)).status_code == 204
    assert (await client.get(url, headers=h)).status_code == 404
    assert (await client.get(f"{API}/interviews", headers=h)).json()["total"] == 2
