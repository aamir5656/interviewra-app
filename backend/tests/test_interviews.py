async def test_other_user_gets_404_everywhere(client: AsyncClient, use_fake_llm) -> None:
    use_fake_llm(tool_responses=["Q1?"], texts=["T"])
    owner, other = await guest(client), await guest(client)
    sid = await start_ok(client, owner)
    url = f"{API}/interviews/{sid}"
    checks = [
        await client.post(f"{url}/answer", json={"content": "hi"}, headers=other),
        await client.get(url, headers=other),
        await client.patch(url, json={"title": "mine"}, headers=other),
        await client.delete(url, headers=other),
        await client.post(f"{url}/end", headers=other),
        await client.get(f"{url}/report", headers=other),
    ]
    assert [r.status_code for r in checks] == [404] * 6
    assert all(r.json()["error"]["code"] in {"not_found"} for r in checks)
    assert (await client.get(url, headers=owner)).status_code == 200
    assert (await client.get(f"{API}/interviews", headers=other)).json()["total"] == 0


